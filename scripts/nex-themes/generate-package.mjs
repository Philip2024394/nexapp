// scripts/nex-themes/generate-package.mjs
//
// NEX Theme Production · Phase A2 · package emission.
// --------------------------------------------------------------------------
// Owner-authorised 2026-10-19. Isolated from production rendering.
//
// Honesty invariants:
//   · Emits a NEW `.package.ts` file into the isolated staging directory
//     `scripts/nex-themes/generated/<slug>/`. NEVER writes to the live
//     `src/app/nex-native/chat-standard/packages/` directory.
//   · If a target path already exists, refuses to overwrite and reports.
//   · The emitted ThemePackage carries BOTH the pre-A1 ColourSystem shape
//     (so the existing engine remains compatible) AND the Phase A1
//     `derivedTokens` field. No runtime surface reads `derivedTokens`
//     today · see the honesty note on the schema itself.
//   · The emission is pure string templating · no AST or codegen library.
//
// Public API:
//   emitPackageFile({ outputDir, slug, name, category, introPath,
//                     wallpaperPath, tokens, colourSystem,
//                     dryRun }) → { path, bytes, overwriteBlocked }

import { promises as fs } from "node:fs";
import * as path from "node:path";

export async function emitPackageFile(args) {
  const {
    outputDir,
    slug,
    name,
    category,
    introPath,
    wallpaperPath,
    tokens,
    colourSystem,
    dryRun = false,
  } = args;

  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    throw new Error(
      `emitPackageFile: slug must be lowercase-hyphenated · got "${slug}"`,
    );
  }

  const outPath = path.join(outputDir, `${slug}.package.ts`);

  if (!dryRun) {
    try {
      await fs.access(outPath);
      return { path: outPath, bytes: 0, overwriteBlocked: true };
    } catch {
      // file does not exist · safe to write
    }
    await fs.mkdir(outputDir, { recursive: true });
  }

  const body = renderPackageSource({
    slug,
    name,
    category,
    introPath,
    wallpaperPath,
    tokens,
    colourSystem,
  });

  // Phase A3 · also emit a JSON sidecar so the dev-only preview route
  // can read the theme by slug without TypeScript parsing. The JSON is
  // a plain data mirror of the exported ThemePackage · it carries no
  // module-system semantics and lives next to the .package.ts file.
  const jsonBody = JSON.stringify(
    {
      identity: {
        id: slug,
        name,
        tagline: `${name} · generated preview`,
        conceptOneLine: `${name} · generated · pending A3 validation`,
        categoryId: category,
      },
      colours: colourSystem,
      personality: "drift",
      intro: {
        kind: "standard",
        videoUrl: introPath,
        scriptedAnimation: null,
        playPolicy: "twice-then-skip",
      },
      wallpaperUrl: wallpaperPath,
      wallpaperScrim: "default",
      derivedTokens: tokens,
    },
    null,
    2,
  );
  const jsonPath = path.join(outputDir, `${slug}.package.json`);

  if (!dryRun) {
    await fs.writeFile(outPath, body, "utf8");
    await fs.writeFile(jsonPath, jsonBody + "\n", "utf8");
  }

  return {
    path: outPath,
    jsonPath,
    bytes: Buffer.byteLength(body, "utf8"),
    overwriteBlocked: false,
    source: body,
  };
}

/** Pure string renderer · deterministic output for a given input. */
function renderPackageSource({
  slug,
  name,
  category,
  introPath,
  wallpaperPath,
  tokens,
  colourSystem,
}) {
  const constName = `${slug.toUpperCase().replace(/-/g, "_")}_PACKAGE`;
  const generatedAt = new Date().toISOString();

  return `// scripts/nex-themes/generated/${slug}/${slug}.package.ts
//
// GENERATED by the NEX Theme Production CLI (Phase A2).
// Generated at ${generatedAt}
//
// Honesty invariants (DO NOT STRIP):
//   · This package was emitted by the baseline palette extractor.
//     Quality gates (contrast / legibility / preview) are PENDING
//     and land in Phase A3. Do not treat this file as production-
//     ready until A3 validation is in place.
//   · This file lives in the ISOLATED staging directory. It is NOT
//     registered with the live-worlds adapter. Migration into
//     src/app/nex-native/chat-standard/packages/ is a separate
//     owner-authorised step.
//   · derivedTokens is populated for the forthcoming A3 gate. No
//     runtime surface reads it today · the engine still resolves
//     colours from the ColourSystem block above.

import type { ThemePackage } from "../../../../src/lib/nex-native/theme-package/types";

export const ${constName}: ThemePackage = {
  identity: {
    id: ${JSON.stringify(slug)},
    name: ${JSON.stringify(name)},
    tagline: ${JSON.stringify(`${name} · generated preview`)},
    conceptOneLine: ${JSON.stringify(`${name} · generated · pending A3 validation`)},
    categoryId: ${JSON.stringify(category)},
  },
  colours: ${JSON.stringify(colourSystem, null, 4).replace(/\n/g, "\n  ")},
  personality: "drift",

  intro: {
    kind: "standard",
    videoUrl: ${JSON.stringify(introPath)},
    scriptedAnimation: null,
    playPolicy: "twice-then-skip",
  },

  wallpaperUrl: ${JSON.stringify(wallpaperPath)},
  wallpaperScrim: "default",

  // Phase A1 derived semantic tokens · see types.ts section 25.
  derivedTokens: ${JSON.stringify(tokens, null, 4).replace(/\n/g, "\n  ")},
};
`;
}
