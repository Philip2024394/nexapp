#!/usr/bin/env node
// Sealed 2026-11-23 · nexapp blueprint map generator
// Greps process.env.XYZ across src/**, scripts/**, .github/workflows/**
// Emits docs/map/env.md. Read-only.

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");
const OUT_FILE = path.join(REPO_ROOT, "docs", "map", "env.md");

const SEARCH_ROOTS = [
  { dir: path.join(REPO_ROOT, "src"), exts: /\.(ts|tsx|js|mjs|cjs)$/ },
  { dir: path.join(REPO_ROOT, "scripts"), exts: /\.(ts|tsx|js|mjs|cjs)$/ },
  { dir: path.join(REPO_ROOT, ".github", "workflows"), exts: /\.(ya?ml)$/ },
];

// Also scan for process.env.X in GitHub workflow YAML (bash blocks).
// And ${{ env.X }} / ${{ secrets.X }} patterns are intentionally skipped — they're
// not Node process.env; the registry is for Node-side consumption.

/**
 * @param {string} dir
 * @param {RegExp} match
 * @returns {Promise<string[]>}
 */
async function walk(dir, match) {
  /** @type {string[]} */
  const out = [];
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch (err) {
    if (err && err.code === "ENOENT") return out;
    throw err;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".next" || entry.name === "__tests__") continue;
      out.push(...(await walk(full, match)));
    } else if (entry.isFile() && match.test(entry.name)) {
      out.push(full);
    }
  }
  return out;
}

/**
 * @param {string} name
 */
function category(name) {
  if (name.startsWith("NEXT_PUBLIC_")) return "NEXT_PUBLIC_*";
  if (name.startsWith("NEX_SUPABASE_") || name.startsWith("SUPABASE_") || name === "NEXT_PUBLIC_NEX_SUPABASE_URL") return "SUPABASE_*";
  if (name.startsWith("STRIPE_") || name.startsWith("NEX_STRIPE_")) return "STRIPE_*";
  if (name.startsWith("CLOUDFLARE_") || name.startsWith("CF_")) return "CLOUDFLARE_*";
  if (name.startsWith("BREVO_")) return "BREVO_*";
  if (name.startsWith("VERCEL_")) return "VERCEL_*";
  if (name.startsWith("NEX_")) return "NEX_*";
  if (name === "NODE_ENV" || name === "CI" || name === "PATH" || name === "HOME") return "RUNTIME_*";
  return "OTHER";
}

function isPublic(name) {
  return name.startsWith("NEXT_PUBLIC_");
}

async function tryReadExampleEnv() {
  const candidates = [".env.local.example", ".env.example", ".env.sample"];
  for (const c of candidates) {
    const p = path.join(REPO_ROOT, c);
    try {
      const txt = await fs.readFile(p, "utf8");
      /** @type {Set<string>} */
      const vars = new Set();
      for (const line of txt.split(/\r?\n/)) {
        const m = line.match(/^\s*([A-Z0-9_]+)\s*=/);
        if (m) vars.add(m[1]);
      }
      return { file: c, vars };
    } catch {
      // continue
    }
  }
  return null;
}

async function main() {
  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });

  /** @type {string[]} */
  let files = [];
  for (const root of SEARCH_ROOTS) {
    files.push(...(await walk(root.dir, root.exts)));
  }

  // name -> array of { file, line, snippet }
  /** @type {Map<string,Array<{file:string,line:number,snippet:string}>>} */
  const hits = new Map();
  const envRe = /process\.env\.([A-Z0-9_]+)/g;

  for (const f of files) {
    let text;
    try {
      text = await fs.readFile(f, "utf8");
    } catch {
      continue;
    }
    const lines = text.split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      envRe.lastIndex = 0;
      let m;
      while ((m = envRe.exec(line))) {
        const name = m[1];
        const relFile = path.relative(REPO_ROOT, f).replaceAll("\\", "/");
        if (!hits.has(name)) hits.set(name, []);
        const arr = hits.get(name);
        arr.push({ file: relFile, line: i + 1, snippet: line.trim().slice(0, 160) });
      }
    }
  }

  // Group by category
  /** @type {Record<string,string[]>} */
  const byCat = {};
  for (const name of hits.keys()) {
    const cat = category(name);
    if (!byCat[cat]) byCat[cat] = [];
    byCat[cat].push(name);
  }
  for (const k of Object.keys(byCat)) byCat[k].sort();

  const example = await tryReadExampleEnv();

  const lines = [];
  lines.push("# Environment Variable Registry");
  lines.push("");
  lines.push("> Auto-generated by `npm run map:env` (or `node scripts/build-env-registry.mjs`).");
  lines.push("> Do not edit by hand — edits will be overwritten. Sealed 2026-11-23.");
  lines.push("");
  lines.push(`- Unique env vars referenced in code: **${hits.size}**`);
  lines.push(`- Files scanned: **${files.length}**`);
  if (example) {
    lines.push(`- Example env file: \`${example.file}\` (${example.vars.size} vars declared)`);
  } else {
    lines.push("- Example env file: (not found)");
  }
  lines.push("");
  lines.push("### Category key");
  lines.push("");
  lines.push("- **NEXT_PUBLIC_*** — exposed to the browser bundle (safe for public values).");
  lines.push("- **SUPABASE_*** — Supabase client/service keys.");
  lines.push("- **STRIPE_*** — Stripe keys and webhook secrets.");
  lines.push("- **CLOUDFLARE_*** — Cloudflare / Workers deploy credentials.");
  lines.push("- **BREVO_*** — Brevo transactional email API.");
  lines.push("- **VERCEL_*** — Vercel deploy metadata (may be legacy — nexapp is on Cloudflare).");
  lines.push("- **NEX_*** — nexapp-specific server-only secrets.");
  lines.push("- **RUNTIME_*** — standard runtime (NODE_ENV, CI, …).");
  lines.push("- **OTHER** — unclassified.");
  lines.push("");

  for (const cat of Object.keys(byCat).sort()) {
    lines.push(`## ${cat}`);
    lines.push("");
    lines.push("| Env Var | Public? | References | Likely purpose (first occurrence) |");
    lines.push("|---|---|---|---|");
    for (const name of byCat[cat]) {
      const refs = hits.get(name);
      const refCount = refs.length;
      const first = refs[0];
      const purpose = first ? first.snippet.replace(/\|/g, "\\|") : "";
      const refSummary = `${refCount} ref${refCount === 1 ? "" : "s"} across ${new Set(refs.map((r) => r.file)).size} file(s)`;
      lines.push(`| \`${name}\` | ${isPublic(name) ? "yes" : "no"} | ${refSummary} | \`${purpose}\` |`);
    }
    lines.push("");
  }

  // Detailed reference list
  lines.push("## Full reference index");
  lines.push("");
  for (const name of Array.from(hits.keys()).sort()) {
    lines.push(`### \`${name}\``);
    const refs = hits.get(name);
    for (const r of refs.slice(0, 20)) {
      lines.push(`- \`${r.file}:${r.line}\``);
    }
    if (refs.length > 20) {
      lines.push(`- … and ${refs.length - 20} more`);
    }
    lines.push("");
  }

  if (example) {
    const declaredNotReferenced = Array.from(example.vars).filter((v) => !hits.has(v)).sort();
    const referencedNotDeclared = Array.from(hits.keys()).filter((v) => !example.vars.has(v)).sort();
    lines.push("## Declared in example but not referenced in code");
    lines.push("");
    if (declaredNotReferenced.length === 0) {
      lines.push("_None._");
    } else {
      for (const v of declaredNotReferenced) lines.push(`- \`${v}\``);
    }
    lines.push("");
    lines.push("## Referenced in code but not declared in example");
    lines.push("");
    if (referencedNotDeclared.length === 0) {
      lines.push("_None._");
    } else {
      for (const v of referencedNotDeclared) lines.push(`- \`${v}\``);
    }
    lines.push("");
  }

  await fs.writeFile(OUT_FILE, lines.join("\n"), "utf8");
  console.log(`env.md written · ${hits.size} unique vars · ${files.length} files scanned · ${lines.length} lines`);
}

main().catch((err) => {
  console.error("build-env-registry failed:", err);
  process.exit(1);
});
