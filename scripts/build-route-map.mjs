#!/usr/bin/env node
// Sealed 2026-11-23 · nexapp blueprint map generator
// Walks src/app/nex-native/**/page.tsx and src/app/api/nex-native/**/route.ts
// Emits docs/map/routes.md. Read-only — does not modify parsed source.

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");
const PAGE_ROOT = path.join(REPO_ROOT, "src", "app", "nex-native");
const API_ROOT = path.join(REPO_ROOT, "src", "app", "api", "nex-native");
const OUT_FILE = path.join(REPO_ROOT, "docs", "map", "routes.md");

const HTTP_METHODS = ["GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"];

/**
 * @param {string} dir
 * @param {string} filename
 * @returns {Promise<string[]>}
 */
async function walk(dir, filename) {
  /** @type {string[]} */
  const out = [];
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch (err) {
    if (err && err.code === "ENOENT") return out;
    throw err;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      // Skip Next.js parallel route internals & test dirs
      if (entry.name === "__tests__" || entry.name === "node_modules") continue;
      out.push(...(await walk(full, filename)));
    } else if (entry.isFile() && entry.name === filename) {
      out.push(full);
    }
  }
  return out;
}

/**
 * Convert an absolute page/route file path into its Next.js route path.
 * @param {string} absFile
 * @param {string} root
 * @returns {string}
 */
function routeFromFile(absFile, root) {
  const rel = path.relative(root, absFile);
  const dir = path.dirname(rel);
  if (dir === "." || dir === "") return "/";
  // Keep Next.js dynamic segments ([slug], [[...slug]], (group)) as-is.
  const parts = dir.split(path.sep);
  return "/" + parts.join("/");
}

/**
 * Peek at the first ~40 lines of a file for directives + known exports.
 * @param {string} file
 */
async function inspectFile(file) {
  const text = await fs.readFile(file, "utf8");
  const head = text.split(/\r?\n/).slice(0, 60).join("\n");
  const isClient = /^\s*["']use client["']/m.test(head);
  const isServer = /^\s*["']use server["']/m.test(head);
  const hasMetadata = /export\s+(const|let|var|async\s+function|function)\s+(metadata|generateMetadata)\b/.test(text);
  /** @type {string[]} */
  const methods = [];
  for (const m of HTTP_METHODS) {
    const re = new RegExp(`export\\s+(?:async\\s+)?(?:function\\s+${m}\\b|const\\s+${m}\\s*=)`);
    if (re.test(text)) methods.push(m);
  }
  return { isClient, isServer, hasMetadata, methods };
}

function mdEscape(s) {
  return s.replace(/\|/g, "\\|");
}

async function main() {
  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });

  const pageFiles = await walk(PAGE_ROOT, "page.tsx");
  const apiFiles = await walk(API_ROOT, "route.ts");

  /** @type {Array<{route:string,file:string,isClient:boolean,isServer:boolean,hasMetadata:boolean}>} */
  const pages = [];
  for (const f of pageFiles) {
    const info = await inspectFile(f);
    pages.push({
      route: "/nex-native" + (routeFromFile(f, PAGE_ROOT) === "/" ? "" : routeFromFile(f, PAGE_ROOT)),
      file: path.relative(REPO_ROOT, f).replaceAll("\\", "/"),
      ...info,
    });
  }
  pages.sort((a, b) => a.route.localeCompare(b.route));

  /** @type {Array<{route:string,file:string,methods:string[]}>} */
  const apis = [];
  for (const f of apiFiles) {
    const info = await inspectFile(f);
    apis.push({
      route: "/api/nex-native" + (routeFromFile(f, API_ROOT) === "/" ? "" : routeFromFile(f, API_ROOT)),
      file: path.relative(REPO_ROOT, f).replaceAll("\\", "/"),
      methods: info.methods,
    });
  }
  apis.sort((a, b) => a.route.localeCompare(b.route));

  const lines = [];
  lines.push("# Route Map");
  lines.push("");
  lines.push("> Auto-generated by `npm run map:routes` (or `node scripts/build-route-map.mjs`).");
  lines.push("> Do not edit by hand — edits will be overwritten. Sealed 2026-11-23.");
  lines.push("");
  lines.push("## Overview");
  lines.push("");
  lines.push(`- Page routes under \`src/app/nex-native\`: **${pages.length}**`);
  lines.push(`- API routes under \`src/app/api/nex-native\`: **${apis.length}**`);
  lines.push("");
  lines.push("## Page routes");
  lines.push("");
  lines.push("| Route | File | Client/Server | Has metadata |");
  lines.push("|---|---|---|---|");
  for (const p of pages) {
    const cs = p.isClient ? "client" : p.isServer ? "server (directive)" : "server (default)";
    lines.push(`| \`${mdEscape(p.route)}\` | \`${mdEscape(p.file)}\` | ${cs} | ${p.hasMetadata ? "yes" : "no"} |`);
  }
  lines.push("");
  lines.push("## API routes");
  lines.push("");
  lines.push("| Method(s) | Route | File |");
  lines.push("|---|---|---|");
  for (const a of apis) {
    const m = a.methods.length ? a.methods.join(", ") : "(none exported)";
    lines.push(`| ${m} | \`${mdEscape(a.route)}\` | \`${mdEscape(a.file)}\` |`);
  }
  lines.push("");

  await fs.writeFile(OUT_FILE, lines.join("\n"), "utf8");
  console.log(`routes.md written · ${pages.length} pages · ${apis.length} api routes · ${lines.length} lines`);
}

main().catch((err) => {
  console.error("build-route-map failed:", err);
  process.exit(1);
});
