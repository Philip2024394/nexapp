// scripts/_tmp/provision-playwright-auth-fixtures.mjs
//
// Sandbox-only · 2026-11-14 · P6 two-context Playwright prep.
// -----------------------------------------------------------------
// Provisions two REAL Supabase auth accounts in the sealed sandbox
// project (kdstoyyeygcopkogqsyv), each linked to a sealed mock
// persona (nex-99901 "Hammerex Products" + nex-99903 "Rosa") so
// Playwright can drive real email/password sign-in in two isolated
// browser contexts.
//
// Hard refuses to run against production. Hard refuses if the env
// does not resolve to sandbox. Idempotent · running twice re-uses
// existing auth rows without creating duplicates.
//
// Email domain: @nex.invalid (RFC 2606 reserved · guaranteed
// unreachable by real mail · clearly a fixture address).
//
// On success writes the two emails + passwords into
// .env.playwright.p6 (gitignored · see .gitignore line added in
// tandem) so the two-context Playwright spec can read them without
// baking secrets into source.

import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { randomBytes } from "node:crypto";

const env = readFileSync(".env.local", "utf8");
function envValue(name) {
  const m = env.match(new RegExp(`^${name}=(.*)$`, "m"));
  return m ? m[1].trim() : null;
}

const url =
  envValue("NEXT_PUBLIC_NEX_SUPABASE_URL") ||
  envValue("NEX_SUPABASE_URL");
const serviceKey = envValue("NEX_SUPABASE_SERVICE_ROLE_KEY");

if (!url || !serviceKey) {
  console.error("STOP · missing NEXT_PUBLIC_NEX_SUPABASE_URL or NEX_SUPABASE_SERVICE_ROLE_KEY");
  process.exit(1);
}
if (!url.includes("kdstoyyeygcopkogqsyv")) {
  console.error(`STOP · not sandbox (url=${url})`);
  process.exit(2);
}
if (url.includes("ijvqdvsvwtwxzcqmoqit")) {
  console.error("STOP · url contains production ref");
  process.exit(3);
}

const admin = createClient(url, serviceKey, {
  auth: { autoRefreshToken: false, persistSession: false },
});

const FIXTURES = [
  {
    label: "customer",
    email: "p6-customer@nex.invalid",
    personaHandle: "nex-99901",
    personaId: "11111111-1111-4111-8111-111111111111",
  },
  {
    label: "seller",
    email: "p6-seller@nex.invalid",
    personaHandle: "nex-99903",
    personaId: "11111111-1111-4111-8111-111111111113",
  },
];

function freshPassword() {
  // 24-char URL-safe base64 · ~144 bits entropy. Rotates on every
  // provisioning run so a leaked .env.playwright.p6 is quickly stale.
  return randomBytes(18).toString("base64url");
}

async function ensureAuthUser(email, password) {
  // Try to find an existing auth.users row with this email via admin list.
  const { data: list, error: listErr } = await admin.auth.admin.listUsers({
    page: 1,
    perPage: 200,
  });
  if (listErr) throw new Error(`admin.listUsers failed: ${listErr.message}`);
  const existing = list.users.find(
    (u) => (u.email ?? "").toLowerCase() === email.toLowerCase(),
  );
  if (existing) {
    // Rotate the password so this run's PW is what Playwright will use.
    const { error: upErr } = await admin.auth.admin.updateUserById(existing.id, {
      password,
      email_confirm: true,
    });
    if (upErr) throw new Error(`admin.updateUserById failed: ${upErr.message}`);
    return { id: existing.id, created: false };
  }
  const { data, error } = await admin.auth.admin.createUser({
    email,
    password,
    email_confirm: true,
  });
  if (error || !data.user)
    throw new Error(`admin.createUser failed: ${error?.message ?? "no user"}`);
  return { id: data.user.id, created: true };
}

async function linkPersona(personaId, personaHandle, authUserId) {
  const { error } = await admin
    .from("nex_account")
    .update({ supabase_user_id: authUserId })
    .eq("id", personaId)
    .eq("is_mock_persona", true);
  if (error) throw new Error(`nex_account link failed (${personaHandle}): ${error.message}`);
}

const emitted = [];
for (const f of FIXTURES) {
  const password = freshPassword();
  const { id, created } = await ensureAuthUser(f.email, password);
  await linkPersona(f.personaId, f.personaHandle, id);
  emitted.push({ ...f, authUserId: id, password, created });
  console.log(
    `[${f.label}] email=${f.email} persona=${f.personaHandle} auth_user_id=${id} ${created ? "(created)" : "(password rotated)"}`,
  );
}

// Persist emails + passwords to a gitignored env file for Playwright.
const dest = ".env.playwright.p6";
const body =
  "# Generated by scripts/_tmp/provision-playwright-auth-fixtures.mjs\n" +
  "# Sandbox-only · regenerated on every run · do NOT commit.\n" +
  "# Playwright spec reads these two pairs for two real sign-ins.\n" +
  emitted
    .map(
      (f) =>
        `PLAYWRIGHT_P6_${f.label.toUpperCase()}_EMAIL=${f.email}\n` +
        `PLAYWRIGHT_P6_${f.label.toUpperCase()}_PASSWORD=${f.password}\n`,
    )
    .join("\n") +
  "\n";
writeFileSync(dest, body);
console.log(`wrote ${dest}`);
