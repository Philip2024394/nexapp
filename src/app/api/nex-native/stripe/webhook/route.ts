// src/app/api/nex-native/stripe/webhook/route.ts
//
// Owner-sealed 2026-11-10 · NEX merchant-direct Stripe webhook endpoint.
// Doctrine (merchant-payments #7): charges hit the SELLER'S connected
// Stripe account directly. NEX never holds funds. This route accepts
// webhooks from connected accounts (Stripe forwards them to the platform
// endpoint with a `Stripe-Account` header identifying the seller). We
// record that header on the audit event so every payment is traceable
// to its merchant.
//
// Trust boundary:
//   · The ONLY trust signal is a valid HMAC-SHA256 signature matching
//     `STRIPE_WEBHOOK_SECRET`. The raw JSON body is NEVER used to
//     authorise anything before signature verification succeeds.
//   · Downstream idempotency is enforced by `commerce-service.markOrderPaid`
//     (which no-ops when the order is already paid/completed/refunded) and
//     by the `recordOrderEvent` audit row carrying the Stripe event id.
//
// Flow:
//   1 · POST only (GET → 405)
//   2 · Read raw body as text (byte-exact for signature verification)
//   3 · Verify `stripe-signature` against `STRIPE_WEBHOOK_SECRET`
//       failure → 400 "invalid signature" (opaque · never leaks which part)
//   4 · Parse JSON into a narrow StripeWebhookEvent
//   5 · Dispatch:
//         · checkout.session.completed → markOrderPaid(orderId, systemActor)
//         · charge.refunded            → record + log (no DB change in P5)
//         · other                      → record + log + 200 (so Stripe stops retrying)
//   6 · Every handled event gets a `recordOrderEvent` row with the Stripe
//       event id as idempotency key in the metadata.

import { NextResponse, type NextRequest } from "next/server";
import {
  verifyStripeSignature,
  parseStripeWebhookEvent,
  extractNexOrderId,
  NEX_STRIPE_SYSTEM_ACTOR_ID,
} from "@/lib/nex-native/payments/stripe-webhook-service";
import { markOrderPaid } from "@/lib/nex-native/commerce-service";
import { recordOrderEvent } from "@/lib/nex-native/order-service";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/** Reject non-POST verbs explicitly. */
export async function GET(): Promise<NextResponse> {
  return NextResponse.json(
    { ok: false, error: "method_not_allowed" },
    { status: 405, headers: { Allow: "POST" } },
  );
}

export async function POST(req: NextRequest): Promise<NextResponse> {
  // 1 · Read raw body FIRST · byte-exact
  const rawBody = await req.text();
  const signatureHeader = req.headers.get("stripe-signature");
  // `Stripe-Account` is set on events generated by a connected account
  // (merchant-direct charges on the seller's Stripe account).
  const connectedAccountId = req.headers.get("stripe-account");

  const secret = process.env.STRIPE_WEBHOOK_SECRET;
  if (!secret) {
    // 500 so Stripe retries while we fix the config. Never echo "secret missing".
    return NextResponse.json(
      { ok: false, error: "config_error" },
      { status: 500 },
    );
  }

  // 2 · Verify signature. Opaque failure response — never leak which part failed.
  if (!verifyStripeSignature(rawBody, signatureHeader, secret)) {
    return NextResponse.json(
      { ok: false, error: "invalid signature" },
      { status: 400 },
    );
  }

  // 3 · Parse the verified payload into a narrow event union.
  const event = parseStripeWebhookEvent(rawBody, connectedAccountId);
  if (!event) {
    // Signature was valid but payload is malformed. 400 so Stripe stops retrying
    // (retrying won't fix a malformed body).
    return NextResponse.json(
      { ok: false, error: "malformed_event" },
      { status: 400 },
    );
  }

  // 4 · Dispatch by event type.
  try {
    if (event.type === "checkout.session.completed") {
      const orderId = extractNexOrderId(event);
      if (!orderId) {
        // Signature-valid event with no NEX order id · log + 200 so Stripe
        // does not retry a permanently-unrecoverable event.
        console.warn(
          "[nex-stripe/webhook] checkout.session.completed with no nex_order_id",
          { stripe_event_id: event.id, session_id: event.data.object.id },
        );
        return NextResponse.json({ ok: true, outcome: "no_order_ref" }, { status: 200 });
      }

      // `markOrderPaid` is idempotent · duplicate deliveries do not
      // double-post the ledger. We ALWAYS record the Stripe event id
      // on `nex_order_event` so replays are visible in the audit trail.
      const result = await markOrderPaid(orderId, NEX_STRIPE_SYSTEM_ACTOR_ID);

      await recordOrderEvent({
        order_id: orderId,
        event: "stripe.checkout.session.completed",
        actor_account_id: NEX_STRIPE_SYSTEM_ACTOR_ID,
        metadata: {
          stripe_event_id: event.id,
          stripe_session_id: event.data.object.id,
          stripe_payment_status: event.data.object.payment_status ?? null,
          stripe_connected_account_id: event.connectedAccountId,
          ledger_entry_id: result.ledgerEntryId,
          order_state_after: result.order.state,
        },
      });

      return NextResponse.json({ ok: true, outcome: "order_paid" }, { status: 200 });
    }

    if (event.type === "charge.refunded") {
      // P5 scope: audit-only · the refund-to-order linkage (metadata.nex_order_id
      // on the PaymentIntent) is populated by the merchant-direct checkout
      // session build-out. For now we log + record a free-standing event row
      // when we can identify an order, otherwise we log and 200.
      const meta = event.data.object.metadata ?? null;
      const orderId = meta && typeof meta.nex_order_id === "string" ? meta.nex_order_id : null;
      if (orderId) {
        await recordOrderEvent({
          order_id: orderId,
          event: "stripe.charge.refunded",
          actor_account_id: NEX_STRIPE_SYSTEM_ACTOR_ID,
          metadata: {
            stripe_event_id: event.id,
            stripe_charge_id: event.data.object.id,
            stripe_amount_refunded: event.data.object.amount_refunded ?? null,
            stripe_connected_account_id: event.connectedAccountId,
          },
        });
      } else {
        console.info(
          "[nex-stripe/webhook] charge.refunded without nex_order_id · logged only",
          { stripe_event_id: event.id, charge_id: event.data.object.id },
        );
      }
      return NextResponse.json({ ok: true, outcome: "refund_logged" }, { status: 200 });
    }

    // Unhandled but signature-valid event · log and 200 so Stripe stops retrying.
    // The union narrows to `{ type: "unhandled"; originalType: string }` here.
    console.info("[nex-stripe/webhook] unhandled event type", {
      stripe_event_id: event.id,
      type: event.originalType,
    });
    return NextResponse.json({ ok: true, outcome: "unhandled" }, { status: 200 });
  } catch (err) {
    // Never echo internal error messages back to Stripe · they would appear
    // verbatim in the Stripe dashboard webhook log. Log server-side only.
    const msg = err instanceof Error ? err.message : String(err);
    console.error("[nex-stripe/webhook] processing failed:", msg);
    return NextResponse.json(
      { ok: false, error: "processing_error" },
      { status: 500 },
    );
  }
}
