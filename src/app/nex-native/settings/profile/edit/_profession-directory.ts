/** Find the category that contains `profession` (case-insensitive).
 *  Returns the first match · the stored value is the profession
 *  string itself so cross-category duplicates (e.g. "Project
 *  manager") are indistinguishable at load time. */
export function findCategoryForProfession(
  profession: string,
): ProfessionCategory | null {
  const needle = profession.trim().toLowerCase();
  if (!needle) return null;
  for (const cat of PROFESSION_DIRECTORY) {
    if (cat.professions.some((p) => p.toLowerCase() === needle)) return cat;
  }
  return null;
}
