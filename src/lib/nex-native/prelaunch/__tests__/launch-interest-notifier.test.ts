// NEX prelaunch · launch-interest notifier (pure composer tests).
// Authored 2026-11-19 · Prompt-7 round 2.
//
// Scope: offline, pure, no network, no provider imports exercised.
// Tests cover only `composeLaunchInterestNotification` — the send
// wrapper is a thin env+Resend bridge and is exercised at a higher
// layer with live provider evidence in a separate (not-yet-authorised)
// phase. These tests PROVE the composer honours the safety contract:
//   · recipient comes from caller arg (never form input)
//   · missing / malformed recipient is a refusal, not a silent pass
//   · submitted email appears verbatim in body (operator can act)
//   · no HTML in the body (no injection surface)
//   · optional UA / IP-hash are truncated (no fingerprint persisted)

import { describe, expect, it } from "vitest";
import { composeLaunchInterestNotification } from "../launch-interest-notifier";

const BASE_INPUT = {
  normalisedEmail: "visitor@example.com",
  source: "nexcorner_landing_v1",
  userAgentOptional: "Mozilla/5.0",
  ipHashOptional: "abcdef0123456789aaaaaaaaaaaaaaaa",
  atIso: "2026-11-19T00:00:00.000Z",
} as const;

describe("composeLaunchInterestNotification · recipient guard", () => {
  it("refuses when recipient is null / undefined / empty / whitespace", () => {
    expect(composeLaunchInterestNotification(null, BASE_INPUT)).toEqual({
      ok: false,
      reason: "no_recipient_configured",
    });
    expect(composeLaunchInterestNotification(undefined, BASE_INPUT)).toEqual({
      ok: false,
      reason: "no_recipient_configured",
    });
    expect(composeLaunchInterestNotification("", BASE_INPUT)).toEqual({
      ok: false,
      reason: "no_recipient_configured",
    });
    expect(composeLaunchInterestNotification("    ", BASE_INPUT)).toEqual({
      ok: false,
      reason: "no_recipient_configured",
    });
  });

  it("refuses when recipient is syntactically invalid", () => {
    expect(
      composeLaunchInterestNotification("not-an-email", BASE_INPUT),
    ).toEqual({ ok: false, reason: "invalid_recipient_shape" });
    expect(
      composeLaunchInterestNotification("foo@bar", BASE_INPUT),
    ).toEqual({ ok: false, reason: "invalid_recipient_shape" });
    expect(
      composeLaunchInterestNotification("@example.com", BASE_INPUT),
    ).toEqual({ ok: false, reason: "invalid_recipient_shape" });
  });

  it("accepts a well-formed recipient and trims surrounding whitespace", () => {
    const result = composeLaunchInterestNotification(
      "  Operator.Name@example.com  ",
      BASE_INPUT,
    );
    expect(result.ok).toBe(true);
    if (result.ok) {
      // Trimmed but case preserved — regex is case-insensitive via toLowerCase.
      expect(result.message.recipient).toBe("Operator.Name@example.com");
    }
  });
});

describe("composeLaunchInterestNotification · body safety", () => {
  it("writes the submitted email verbatim into the plain-text body", () => {
    const result = composeLaunchInterestNotification(
      "ops@nex.example",
      BASE_INPUT,
    );
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.message.text).toContain("visitor@example.com");
      expect(result.message.text).toContain("nexcorner_landing_v1");
      expect(result.message.text).toContain("2026-11-19T00:00:00.000Z");
    }
  });

  it("subject carries only the fact of a new signup — no email or UA", () => {
    const result = composeLaunchInterestNotification(
      "ops@nex.example",
      BASE_INPUT,
    );
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.message.subject).toBe(
        "NEX prelaunch · new launch-interest signup",
      );
      expect(result.message.subject).not.toContain("visitor@example.com");
      expect(result.message.subject).not.toContain("Mozilla");
    }
  });

  it("body is plain text — no HTML tags produced", () => {
    const result = composeLaunchInterestNotification(
      "ops@nex.example",
      {
        ...BASE_INPUT,
        // Hostile content in optional fields must NOT escape into HTML
        // because we never emit HTML. Verify the body stays plain text.
        userAgentOptional: "<script>alert('x')</script>",
      },
    );
    expect(result.ok).toBe(true);
    if (result.ok) {
      // The literal characters may appear (we do not sanitise plain
      // text) but there must be no HTML wrapper generated by us.
      expect(result.message.text).not.toMatch(/<html|<body|<br\/?>/i);
    }
  });

  it("truncates a long user-agent to 200 chars", () => {
    const longUa = "A".repeat(500);
    const result = composeLaunchInterestNotification("ops@nex.example", {
      ...BASE_INPUT,
      userAgentOptional: longUa,
    });
    expect(result.ok).toBe(true);
    if (result.ok) {
      // 200 A's present; 201 A's absent.
      expect(result.message.text).toContain("A".repeat(200));
      expect(result.message.text).not.toContain("A".repeat(201));
    }
  });

  it("emits only a 12-char prefix of the ip-hash, never the full value", () => {
    const fullHash = "0123456789abcdef0123456789abcdef";
    const result = composeLaunchInterestNotification("ops@nex.example", {
      ...BASE_INPUT,
      ipHashOptional: fullHash,
    });
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.message.text).toContain("0123456789ab");
      expect(result.message.text).not.toContain(fullHash);
    }
  });

  it("records 'not captured' markers when optional fields are missing", () => {
    const result = composeLaunchInterestNotification("ops@nex.example", {
      normalisedEmail: "visitor@example.com",
      source: "nexcorner_landing_v1",
      userAgentOptional: null,
      ipHashOptional: null,
      atIso: null,
    });
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.message.text).toContain("User-Agent:   <not captured>");
      expect(result.message.text).toContain("IP-hash: <not captured>");
      expect(result.message.text).toContain("<unset>");
    }
  });
});

describe("composeLaunchInterestNotification · recipient is never caller-derived", () => {
  it("ignores any email in `input` when choosing the recipient", () => {
    // This is the hardening check: even if a bad caller passed a
    // submitted email that looked like an admin address, the composer
    // STILL routes to the recipient argument. The function signature
    // enforces this — this test documents the guarantee.
    const result = composeLaunchInterestNotification(
      "ops@nex.example",
      {
        ...BASE_INPUT,
        normalisedEmail: "attacker@evil.example",
      },
    );
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.message.recipient).toBe("ops@nex.example");
      // attacker address shows up in the BODY (operator sees it) but is
      // NEVER elevated to a To: recipient.
      expect(result.message.text).toContain("attacker@evil.example");
    }
  });
});
